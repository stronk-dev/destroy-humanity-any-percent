import assert from "node:assert/strict";

import { generatedGoKeys } from "./copy-pipeline.mjs";

// Whole-output goldens are deliberately independent of the renderer. No Go
// binary is required by the client generation/check lane.
const fixtures = [
  { name: "empty", args: [[], [], []], expected: `// Code generated by \`make copy-generate\`; DO NOT EDIT.
package copykeys

func All() []string {
	return []string{}
}

// CompanionKeys lists the keys whose tone is companion (Pet Adoption v1 PA8.6).
func CompanionKeys() []string {
	return []string{}
}
` },
  { name: "single default", args: [["fixture.one"]], expected: `// Code generated by \`make copy-generate\`; DO NOT EDIT.
package copykeys

const FixtureOne = "fixture.one"

func All() []string {
	return []string{"fixture.one"}
}

// CompanionKeys lists the keys whose tone is companion (Pet Adoption v1 PA8.6).
func CompanionKeys() []string {
	return []string{}
}
` },
  { name: "multiple input order", args: [["fixture.second", "fixture.first"]], expected: `// Code generated by \`make copy-generate\`; DO NOT EDIT.
package copykeys

const FixtureSecond = "fixture.second"
const FixtureFirst = "fixture.first"

func All() []string {
	return []string{"fixture.second", "fixture.first"}
}

// CompanionKeys lists the keys whose tone is companion (Pet Adoption v1 PA8.6).
func CompanionKeys() []string {
	return []string{}
}
` },
  { name: "independent lists", args: [["fixture.producer"], ["fixture.a", "fixture.b", "fixture.c"], ["fixture.c", "fixture.a"]], expected: `// Code generated by \`make copy-generate\`; DO NOT EDIT.
package copykeys

const FixtureProducer = "fixture.producer"

func All() []string {
	return []string{"fixture.a", "fixture.b", "fixture.c"}
}

// CompanionKeys lists the keys whose tone is companion (Pet Adoption v1 PA8.6).
func CompanionKeys() []string {
	return []string{"fixture.c", "fixture.a"}
}
` },
  { name: "companion only", args: [[], [], ["fixture.companion"]], expected: `// Code generated by \`make copy-generate\`; DO NOT EDIT.
package copykeys

func All() []string {
	return []string{}
}

// CompanionKeys lists the keys whose tone is companion (Pet Adoption v1 PA8.6).
func CompanionKeys() []string {
	return []string{"fixture.companion"}
}
` },
];

function assertGeneration(actual, expected, name) {
  assert.equal(actual, expected, `generated Go fixture: ${name}`);
}

for (const fixture of fixtures) {
  assertGeneration(generatedGoKeys(...fixture.args), fixture.expected, fixture.name);
}
assert.throws(() => generatedGoKeys(["fixture.same_key", "fixture.same.key"]), /generated Go constant names collide/);

const expected = fixtures[3].expected;
const corruptions = [
  expected.replace('func All() []string {\n\treturn []string{"fixture.a", "fixture.b", "fixture.c"}\n}', 'func All() []string { return []string{"fixture.a", "fixture.b", "fixture.c"} }'),
  expected.replace("\treturn", "  return"),
  expected.replace('"fixture.a", "fixture.b", "fixture.c"', '"fixture.b", "fixture.a", "fixture.c"'),
  expected.replace(', "fixture.b"', ""),
  expected.replace('[]string{"fixture.c", "fixture.a"}', '[]string{"fixture.a", "fixture.b", "fixture.c"}'),
  expected.replace('const FixtureProducer = "fixture.producer"', 'const FixtureProducer = "fixture.wrong"'),
];
for (const [index, corrupted] of corruptions.entries()) {
  assert.notEqual(corrupted, expected, `generation corruption ${index} did not land`);
  assert.throws(() => assertGeneration(corrupted, expected, `corruption ${index}`), /generated Go fixture/);
}
console.log(`copy Go generation fixtures ok: ${fixtures.length} goldens, collision refusal, ${corruptions.length} rejected corruptions`);
